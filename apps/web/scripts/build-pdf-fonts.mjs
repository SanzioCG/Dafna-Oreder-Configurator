/**
 * Writes server/pdfFonts.ts: the Inter subsets (latin, cyrillic, cyrillic-ext; regular + bold)
 * as base64, so the order PDF (server/orderPdf.ts) can draw Uzbek and Russian text in the
 * self-contained api/ bundles. Inter is licensed under the SIL Open Font License 1.1.
 *
 *   node scripts/build-pdf-fonts.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'node_modules/@fontsource/inter/files');
const SUBSETS = ['latin', 'cyrillic', 'cyrillic-ext'];
const out = [
  '// GENERATED by scripts/build-pdf-fonts.mjs — do not edit.',
  '// Inter (SIL Open Font License 1.1) subsets, WOFF, base64.',
  '',
];
for (const weight of [400, 700]) {
  const list = SUBSETS.map(
    (s) => `  '${readFileSync(join(dir, `inter-${s}-${weight}-normal.woff`)).toString('base64')}',`,
  );
  out.push(`export const INTER_${weight}: string[] = [`, ...list, '];', '');
}
writeFileSync(join(root, 'server/pdfFonts.ts'), out.join('\n'));
console.log('server/pdfFonts.ts written');
