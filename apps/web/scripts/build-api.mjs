/**
 * Bundles the Vercel Functions (server/entries/*.ts) into self-contained ESM files in api/.
 * The bundles are committed: Vercel then runs plain JS and never has to compile TypeScript from
 * the workspace engine package. A test (server/bundle.test.ts) fails when a bundle is stale.
 *
 *   node scripts/build-api.mjs          write api/*.js
 *   node scripts/build-api.mjs setup    build + run the sheet setup (needs Google env vars)
 */
import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const API_ENTRIES = ['submit', 'retry-telegram'];
const BANNER = '// GENERATED by scripts/build-api.mjs from server/ — do not edit.';

/** Bundles one entry in memory; returns its source text. */
export async function bundleEntry(name) {
  const result = await build({
    entryPoints: [join(root, 'server/entries', `${name}.ts`)],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    write: false,
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  // normalise line endings so Windows and CI produce identical bundles
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

async function main() {
  if (process.argv[2] === 'setup') {
    const out = join(root, 'node_modules/.cache/dafna/setup-sheet.mjs');
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, await bundleEntry('setup-sheet'));
    const r = spawnSync(process.execPath, [out], { stdio: 'inherit' });
    process.exit(r.status ?? 1);
  }
  mkdirSync(join(root, 'api'), { recursive: true });
  for (const name of API_ENTRIES) {
    writeFileSync(join(root, 'api', `${name}.js`), await bundleEntry(name));
    console.log(`api/${name}.js`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
