/**
 * Writes server/pdfLogo.ts: the Dafna logo (public/brand/dafna-logo.svg) as path data for the
 * PDFs (pdf-lib draws SVG paths, not SVG files).
 *
 *   node scripts/build-pdf-logo.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const svg = readFileSync(join(root, 'public/brand/dafna-logo.svg'), 'utf8').replace(
  /<metadata>[\s\S]*?<\/metadata>/,
  '',
);
const [, w, h] = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
const paths = [...svg.matchAll(/<path d="([^"]+)"([^>]*)>/g)].map(([, d, attrs]) => {
  const fill = /fill="(#[0-9A-Fa-f]{6})"/.exec(attrs)?.[1] ?? '#000000';
  const [, tx = '0', ty = '0'] = /translate\(([-\d.]+)[ ,]([-\d.]+)\)/.exec(attrs) ?? [];
  return { d: d.trim(), fill, tx: Number(tx), ty: Number(ty) };
});
writeFileSync(
  join(root, 'server/pdfLogo.ts'),
  [
    '// GENERATED by scripts/build-pdf-logo.mjs from public/brand/dafna-logo.svg — do not edit.',
    `export const LOGO_VIEWBOX = { width: ${w}, height: ${h} };`,
    `export const LOGO_PATHS: { d: string; fill: string; tx: number; ty: number }[] = ${JSON.stringify(paths)};`,
    '',
  ].join('\n'),
);
console.log(`server/pdfLogo.ts written (${paths.length} paths)`);
